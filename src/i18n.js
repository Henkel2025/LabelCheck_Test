function normalizeLanguage(value) {
  const short = String(value || "").toLowerCase().split("-")[0];
  return SUPPORTED.has(short) ? short : "de";
}

let currentLanguage = (() => {
  try { return normalizeLanguage(globalThis.localStorage?.getItem(STORAGE_KEY) || "de"); }
  catch { return "de"; }
})();

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(language) {
  currentLanguage = normalizeLanguage(language);
  try { globalThis.localStorage?.setItem(STORAGE_KEY, currentLanguage); } catch { /* optional */ }
  if (globalThis.document?.documentElement) globalThis.document.documentElement.lang = currentLanguage;
  return currentLanguage;
}

export function t(key, variables = {}) {
  const template = translations[currentLanguage]?.[key] ?? translations.de[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ""));
}

export function applyStaticTranslations(root = globalThis.document) {
  if (!root?.querySelectorAll) return;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
}
